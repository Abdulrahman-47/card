"""Builds the QR code shown on the tag page.

Run from the repository root:  python3 tools/make_qr.py
Needs segno (pip install segno). Writes assets/js/qr-data.js, which the
page turns into a styled SVG. Change QR_URL and run it again to point the
QR code somewhere else.
"""
from pathlib import Path

import segno

QR_URL = "https://abdulrahman-47.github.io/card/"

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "js" / "qr-data.js"


def main():
    # Highest error correction, so the yarn-ball badge in the middle can
    # cover a few modules and the code still scans.
    qr = segno.make(QR_URL, error="h", micro=False)
    rows = ["".join("1" if cell else "0" for cell in row) for row in qr.matrix]
    body = ",\n".join(f"    '{row}'" for row in rows)
    OUT.write_text(
        "// Generated by tools/make_qr.py. Run it again if the link changes.\n"
        "window.BOOKLET_QR = {\n"
        f"  url: '{QR_URL}',\n"
        "  rows: [\n"
        f"{body},\n"
        "  ],\n"
        "};\n"
    )
    print(f"{OUT.relative_to(ROOT)}: version {qr.version}, {len(rows)}x{len(rows)} modules, mask {qr.mask}")


if __name__ == "__main__":
    main()
